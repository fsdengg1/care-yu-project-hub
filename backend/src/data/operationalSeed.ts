const hoursAgo = (hours: number) => new Date(Date.now() - hours * 3600000).toISOString();
const daysAgo = (days: number) => hoursAgo(days * 24);

function makeLead(params: {
  id: string;
  number: string;
  title: string;
  customer: string;
  type: Lead['customer_type'];
  vertical: Lead['business_vertical'];
  value: number;
  stage: PipelineStage;
  status: LeadStatus;
  priority?: Lead['priority'];
  createdHoursAgo?: number;
}): Lead {
  const created = hoursAgo(params.createdHoursAgo ?? 48);
  return {
    id: params.id,
    lead_number: params.number,
    title: params.title,
    customer_name: params.customer,
    customer_type: params.type,
    business_vertical: params.vertical,
    created_by: 'Sharadha Patil',
    created_by_id: 'u-bh',
    created_by_role: 'Business Head',
    sales_owner: 'Arivan',
    sales_owner_id: 'u-pm',
    lead_date: created,
    priority: params.priority ?? 'High',
    status: params.status,
    customer_contact: 'Operations Head',
    requirement_summary: params.title,
    detailed_requirement: `${params.title} for ${params.customer}.`,
    application: params.title,
    customer_budget: `₹ ${params.value.toLocaleString('en-IN')}`,
    estimated_opportunity_value: String(params.value),
    expected_value: params.value,
    pipeline_stage: params.stage,
    currency: 'INR',
    created_at: created,
    updated_at: created,
  };
}

